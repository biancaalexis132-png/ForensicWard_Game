#!/usr/bin/env python3
"""Copy the owner-approved static graphic-novel panels into the project, unchanged.

Source: ForensicWard_Static_Graphic_Novel_Cutscenes_Final_v1.zip (the owner's
package, approved 2026-10-19 for Chapters 1-5). The owner asked that the art is
not regenerated, repainted, restyled or replaced, so this script only copies
bytes: every panel PNG lands byte-identical in
assets/cutscenes/static_gn_v1/ch0N/ and its SHA-256 is recorded in that
folder's manifest.json. Nothing is resized, recompressed or painted over.

Usage:
    python3 tools/cutscenes/import_static_graphic_novel.py <zip> --chapter 1 [--chapter 2 ...]

The package's own manifest.json gives the panel order. The cutscene JSON files in
data/cutscenes/ (cs_ch0N_static_gn.json) are authored by hand against the
CutsceneDirector schema; this script does not write them.
"""
import argparse
import hashlib
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = "ForensicWard_Static_Graphic_Novel_Cutscenes_Final_v1"
OUT = ROOT / "assets/cutscenes/static_gn_v1"
APPROVAL = (
    "Owner approved the Static Graphic-Novel Cutscenes Final v1 artwork for Chapters 1-5 "
    "on 2026-10-19 in the Forensics Game project thread. Do not regenerate, repaint, "
    "restyle or replace without the owner's permission."
)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("zip", type=Path)
    parser.add_argument("--chapter", type=int, action="append", required=True)
    args = parser.parse_args()
    with zipfile.ZipFile(args.zip) as archive:
        package = json.loads(archive.read(f"{PACKAGE}/manifest.json"))
        chapters = {c["chapter"]: c for c in package["chapters"]}
        for number in args.chapter:
            import_chapter(archive, chapters[number], args.zip.name)


def import_chapter(archive: zipfile.ZipFile, chapter: dict, zip_name: str) -> None:
    folder = OUT / f"ch{chapter['chapter']:02d}"
    folder.mkdir(parents=True, exist_ok=True)
    assets = []
    for panel in chapter["panels"]:
        data = archive.read(f"{PACKAGE}/{panel['path']}")
        target = folder / Path(panel["path"]).name
        target.write_bytes(data)
        assets.append({
            "path": target.relative_to(ROOT).as_posix(),
            "source": f"owner_supplied:{zip_name}/{PACKAGE}/{panel['path']}",
            "package_panel_id": panel["id"],
            "size": [panel["width"], panel["height"]],
            "sha256": hashlib.sha256(data).hexdigest(),
            "modified": "none (byte-identical copy)",
        })
    manifest = {
        "schema_version": 1,
        "_note": "Generated by tools/cutscenes/import_static_graphic_novel.py. Do not edit by hand.",
        "review_status": "OWNER_APPROVED_ART_REVIEW_ONLY_PLACEMENT",
        "art_approval": APPROVAL,
        "placement": "Review-only (manual preview). Not enabled in the campaign until the owner approves placement after testing.",
        "licence": "Owner-supplied generated illustrations from the owner's own package; tool and licence terms as recorded by the owner (not verified in this repository).",
        "warnings": [
            "Legible paperwork, dates, names, diagnoses and record numbers in the art are illustrative only, never clinical or story data or evidence.",
            "The art shows one fixed protagonist appearance and staff/patient looks that may differ from the 3D character models.",
        ],
        "chapter": chapter["chapter"],
        "chapter_title_in_art": chapter["title"],
        "assets": assets,
    }
    (folder / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"ch{chapter['chapter']:02d}: {len(assets)} panels -> {folder.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
